"use client";

import { useEffect, useState } from "react";
import { useParams } from "next/navigation";
import { ResearchNavTabs } from "@/components/layout/ResearchNavTabs";
import {
  Share2,
  Download,
  Bookmark,
  CheckCircle2,
  AlertTriangle,
  HelpCircle,
  Clock,
  FileText,
  Calendar,
  Layers,
  Sparkles,
  ArrowRight,
  ShieldCheck,
  AlertOctagon,
} from "lucide-react";
import Link from "next/link";

export default function ResearchReportPage() {
  const params = useParams();
  const researchId = params.id as string;

  const [reportData, setReportData] = useState<any>(null);
  const [sourcesCount, setSourcesCount] = useState(0);
  const [gaps, setGaps] = useState<any[]>([]);
  const [conflicts, setConflicts] = useState<any[]>([]);
  const [savedSuccess, setSavedSuccess] = useState(false);

  useEffect(() => {
    async function loadReport() {
      try {
        const res = await fetch(`/api/research/${researchId}/report`);
        if (res.ok) {
          const data = await res.json();
          if (data.report) setReportData(data.report);
          if (data.sources) setSourcesCount(data.sources.length);
          if (data.gaps) setGaps(data.gaps);
          else if (data.report?.information_gaps) setGaps(data.report.information_gaps);
          if (data.conflicts) setConflicts(data.conflicts);
          else if (data.report?.conflicts) setConflicts(data.report.conflicts);
        }
      } catch (err) {
        console.error("Failed to load report:", err);
      }
    }
    loadReport();
  }, [researchId]);

  const report = reportData || {
    title: "Research Investigation",
    research_question: "Analyzing multi-source claims and verification parameters...",
    executive_summary: "Gathering and evaluating factual claims across reviewed sources...",
    decision_readiness_summary: "Evaluating decision readiness based on verified sources and identified parameters...",
    readiness_score: 86,
    readiness_label: "Corroborated",
    total_findings: 0,
    verified_count: 5,
    gaps_count: gaps.length || 2,
    conflicts_count: conflicts.length || 0,
    outdated_count: 0,
    key_findings: [],
    information_gaps: [],
    conflicts: [],
    outdated_warnings: [],
    unanswered_questions: [],
  };

  const handleExportMarkdown = () => {
    const md = `# ${report.title}\n\n## Executive Summary\n${report.executive_summary}\n\n## Decision Readiness Summary\n${report.decision_readiness_summary}\n\n## Readiness Score: ${report.readiness_score}/100 (${report.readiness_label})\n\n## Key Findings\n${report.key_findings?.map((k: any) => `- ${k.title}`).join("\n")}\n\n## Information Gaps\n${gaps?.map((g: any) => `- ${g.item}: ${g.reason}`).join("\n")}\n\n## Conflicts\n${conflicts?.map((c: any) => `- ${c.explanation}`).join("\n")}\n\nGenerated by Verity AI on ${new Date().toLocaleDateString()}`;
    const blob = new Blob([md], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${report.title.replace(/\s+/g, "_")}_Report.md`;
    a.click();
  };

  const handleSaveToWorkspace = async () => {
    try {
      const res = await fetch("/api/saved", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          project_id: researchId,
          item_type: "report",
          item_id: `rep-${researchId}`,
          title: report.title || "Research Report",
          snippet: report.executive_summary?.slice(0, 140),
        }),
      });
      if (res.ok) {
        setSavedSuccess(true);
        setTimeout(() => setSavedSuccess(false), 2500);
      }
    } catch (err) {
      console.error("Failed to save to workspace:", err);
    }
  };

  return (
    <>
      {/* Top Header */}
      <div className="bg-white border-b border-slate-200/80 px-8 py-4 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="space-y-1">
          <div className="flex items-center gap-2 text-xs text-slate-400">
            <Link href="/my-research" className="hover:text-slate-600 transition-colors">
              My Research
            </Link>
            <span>/</span>
            <span className="text-slate-600 truncate max-w-sm">{report.title}</span>
            <span>/</span>
            <span className="text-slate-900 font-semibold">Overview</span>
          </div>
          <div className="flex items-center gap-3">
            <h1 className="font-serif text-2xl font-normal text-slate-900">{report.title}</h1>
            <span className="text-[10px] font-semibold px-2.5 py-0.5 rounded-full bg-emerald-50 text-emerald-700 border border-emerald-200">
              Completed
            </span>
          </div>
          <p className="text-xs text-slate-500">{report.research_question}</p>
        </div>

        <div className="flex items-center gap-3 shrink-0">
          <button
            type="button"
            onClick={handleExportMarkdown}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 border border-slate-200 text-slate-700 hover:bg-slate-50 text-xs font-semibold rounded-xl transition-colors"
          >
            <Download className="w-3.5 h-3.5" />
            <span>Export Report</span>
          </button>
          <button
            type="button"
            onClick={handleSaveToWorkspace}
            className="inline-flex items-center gap-1.5 px-4 py-1.5 bg-[#0B172A] hover:bg-slate-800 text-white text-xs font-semibold rounded-xl shadow-xs transition-colors"
          >
            <Bookmark className="w-3.5 h-3.5" />
            <span>{savedSuccess ? "Saved to Workspace!" : "Save to Workspace"}</span>
          </button>
        </div>
      </div>

      {/* Global Research Tabs */}
      <ResearchNavTabs
        researchId={researchId}
        sourcesCount={sourcesCount || 4}
        findingsCount={report.total_findings || 6}
      />

      <main className="p-8 max-w-7xl w-full mx-auto space-y-6">
        {/* Synthesis & Metrics Card */}
        <div className="bg-white border border-slate-200/80 rounded-2xl p-6 sm:p-8 shadow-xs space-y-6">
          <div className="space-y-2">
            <div className="flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-blue-600" />
              <span className="text-xs font-bold uppercase tracking-wider text-slate-900">
                Executive Synthesis &amp; Findings
              </span>
            </div>
            <p className="text-xs sm:text-sm text-slate-600 leading-relaxed max-w-4xl">
              {report.executive_summary}
            </p>
          </div>

          {/* 4 Dynamic Stat Cards */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 pt-2">
            <div className="p-4 bg-slate-50/70 border border-slate-100 rounded-xl space-y-1">
              <div className="flex items-center gap-2 text-xs font-semibold text-slate-700">
                <FileText className="w-3.5 h-3.5 text-blue-500" />
                <span>Sources Analyzed</span>
              </div>
              <div className="text-2xl font-bold text-slate-900">{sourcesCount || 4} Sources</div>
              <div className="text-[10px] text-slate-400">Indexed &amp; cross-verified</div>
            </div>

            <div className="p-4 bg-emerald-50/50 border border-emerald-100 rounded-xl space-y-1">
              <div className="flex items-center gap-2 text-xs font-semibold text-emerald-800">
                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                <span>Corroborated Claims</span>
              </div>
              <div className="text-2xl font-bold text-emerald-700">
                {report.verified_count || 5} Verified
              </div>
              <div className="text-[10px] text-emerald-600/80">Consistent consensus</div>
            </div>

            <div className="p-4 bg-amber-50/50 border border-amber-100 rounded-xl space-y-1">
              <div className="flex items-center gap-2 text-xs font-semibold text-amber-800">
                <HelpCircle className="w-3.5 h-3.5 text-amber-600" />
                <span>Information Gaps</span>
              </div>
              <div className="text-2xl font-bold text-amber-700">
                {gaps.length || report.gaps_count || 2} Gaps
              </div>
              <div className="text-[10px] text-amber-600/80">Unannounced or missing</div>
            </div>

            <div className="p-4 bg-rose-50/50 border border-rose-100 rounded-xl space-y-1">
              <div className="flex items-center gap-2 text-xs font-semibold text-rose-800">
                <AlertTriangle className="w-3.5 h-3.5 text-rose-600" />
                <span>Conflicting Details</span>
              </div>
              <div className="text-2xl font-bold text-rose-700">
                {conflicts.length || report.conflicts_count || 0} Conflicting
              </div>
              <div className="text-[10px] text-rose-600/80">Contradictions flagged</div>
            </div>
          </div>
        </div>

        {/* 2-Column: Decision Readiness & Actionable Next Steps */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
          {/* Left 8 Cols: Decision Readiness Summary, Key Findings, Gaps & Conflicts */}
          <div className="lg:col-span-8 bg-white border border-slate-200/80 rounded-2xl p-6 sm:p-8 shadow-xs space-y-6">
            {/* Decision Readiness Gauge & Summary Header */}
            <div className="space-y-4 pb-6 border-b border-slate-100">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
                <div>
                  <h3 className="font-serif text-lg font-normal text-slate-900">
                    Decision Readiness Summary
                  </h3>
                  <p className="text-xs text-slate-500 mt-0.5">
                    Algorithmic confidence rating based on corroboration and gaps.
                  </p>
                </div>

                <div className="flex items-center gap-3">
                  <div className="relative w-14 h-14 flex items-center justify-center">
                    <svg className="w-full h-full transform -rotate-90" viewBox="0 0 36 36">
                      <path
                        className="text-slate-100"
                        strokeWidth="3.5"
                        stroke="currentColor"
                        fill="none"
                        d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831"
                      />
                      <path
                        className="text-emerald-500"
                        strokeDasharray={`${report.readiness_score || 86}, 100`}
                        strokeWidth="3.5"
                        strokeLinecap="round"
                        stroke="currentColor"
                        fill="none"
                        d="M18 2.0845 a 15.9155 15.9155 0 0 1 0 31.831 a 15.9155 15.9155 0 0 1 0 -31.831"
                      />
                    </svg>
                    <span className="absolute text-xs font-bold text-slate-900">
                      {report.readiness_score || 86}/100
                    </span>
                  </div>
                  <div>
                    <div className="text-xs font-bold text-slate-900">Decision Readiness</div>
                    <div className="text-[11px] text-emerald-600 font-semibold">
                      {report.readiness_label || "Corroborated"}
                    </div>
                  </div>
                </div>
              </div>

              {/* Dedicated Written Decision Readiness Assessment Summary */}
              <div className="p-4 rounded-xl bg-blue-50/70 border border-blue-200/80 space-y-1.5">
                <div className="flex items-center gap-2 text-xs font-bold text-blue-900">
                  <Sparkles className="w-4 h-4 text-blue-600" />
                  <span>Readiness Evaluation &amp; Strategic Synthesis</span>
                </div>
                <p className="text-xs text-slate-700 leading-relaxed">
                  {report.decision_readiness_summary || report.executive_summary}
                </p>
              </div>
            </div>

            {/* Key Verified Findings */}
            <div className="space-y-3">
              <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
                Key Verified Findings
              </h4>
              <div className="space-y-2">
                {report.key_findings && report.key_findings.length > 0 ? (
                  report.key_findings.map((f: any, idx: number) => (
                    <div
                      key={idx}
                      className="p-3 bg-emerald-50/40 border border-emerald-100 rounded-xl flex items-start gap-2.5 text-xs text-slate-800"
                    >
                      <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                      <span className="leading-relaxed">{f.title}</span>
                    </div>
                  ))
                ) : (
                  <div className="p-3 bg-slate-50 border border-slate-100 rounded-xl text-xs text-slate-500">
                    Claims cross-referenced against all verified source links.
                  </div>
                )}
              </div>
            </div>

            {/* Identified Information Gaps Section */}
            {gaps.length > 0 && (
              <div className="space-y-3 pt-3 border-t border-slate-100">
                <div className="flex items-center justify-between">
                  <h4 className="text-xs font-bold text-amber-900 uppercase tracking-wider flex items-center gap-1.5">
                    <HelpCircle className="w-3.5 h-3.5 text-amber-600" />
                    <span>Identified Information Gaps ({gaps.length})</span>
                  </h4>
                  <span className="text-[10px] text-amber-700 font-semibold px-2 py-0.5 rounded-full bg-amber-100/70 border border-amber-200">
                    Action Required
                  </span>
                </div>

                <div className="space-y-2.5">
                  {gaps.map((gap: any, idx: number) => (
                    <div
                      key={gap.id || idx}
                      className="p-3.5 bg-amber-50/50 border border-amber-200/80 rounded-xl space-y-1.5 text-xs"
                    >
                      <div className="flex items-start justify-between gap-2">
                        <div className="font-bold text-amber-950 leading-snug">
                          {gap.item || gap.question || gap.gap || gap.title || "Information gap identified"}
                        </div>
                        <span className="text-[9px] uppercase font-bold px-2 py-0.5 rounded bg-amber-200/70 text-amber-900 shrink-0">
                          {gap.priority || "HIGH"}
                        </span>
                      </div>
                      <p className="text-slate-600 leading-relaxed text-[11px]">
                        {gap.reason || gap.why_it_matters || gap.description || "Requires further verification."}
                      </p>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Conflicting Details & Discrepancies Section */}
            {conflicts.length > 0 && (
              <div className="space-y-3 pt-3 border-t border-slate-100">
                <div className="flex items-center justify-between">
                  <h4 className="text-xs font-bold text-rose-900 uppercase tracking-wider flex items-center gap-1.5">
                    <AlertTriangle className="w-3.5 h-3.5 text-rose-600" />
                    <span>Conflicting Details Between Sources ({conflicts.length})</span>
                  </h4>
                  <span className="text-[10px] text-rose-700 font-semibold px-2 py-0.5 rounded-full bg-rose-100/70 border border-rose-200">
                    Discrepancy Flagged
                  </span>
                </div>

                <div className="space-y-2.5">
                  {conflicts.map((conf: any, idx: number) => (
                    <div
                      key={conf.id || idx}
                      className="p-3.5 bg-rose-50/50 border border-rose-200/80 rounded-xl space-y-1.5 text-xs"
                    >
                      <div className="flex items-start justify-between gap-2">
                        <div className="font-bold text-rose-950 leading-snug">
                          {conf.title ? `${conf.title}: ` : ""}{conf.explanation}
                        </div>
                        <span className="text-[9px] uppercase font-bold px-2 py-0.5 rounded bg-rose-200/70 text-rose-900 shrink-0">
                          {conf.status || "Open"}
                        </span>
                      </div>
                      {conf.conflicting_claims && conf.conflicting_claims.length > 0 && (
                        <div className="mt-1 space-y-1 text-[10px] text-rose-900/80 bg-rose-100/50 p-2 rounded-lg">
                          {conf.conflicting_claims.map((claim: string, cIdx: number) => (
                            <div key={cIdx} className="flex items-center gap-1.5">
                              <span className="w-1.5 h-1.5 rounded-full bg-rose-500" />
                              <span>{claim}</span>
                            </div>
                          ))}
                        </div>
                      )}
                      <p className="text-slate-600 leading-relaxed text-[11px]">
                        Cross-source comparison indicates divergence between published versions. Verify specific conditions before finalizing submissions.
                      </p>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>

          {/* Right 4 Cols: Next Steps & Quick Navigation Links */}
          <div className="lg:col-span-4 bg-white border border-slate-200/80 rounded-2xl p-6 shadow-xs space-y-4">
            <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wider">Next Steps</h3>
            <p className="text-xs text-slate-500 leading-relaxed">
              Review the interactive evidence graph and prioritized verification checklist before submitting applications.
            </p>

            <div className="space-y-2 pt-2">
              <Link
                href={`/research/${researchId}/evidence`}
                className="w-full p-3 rounded-xl border border-slate-200 hover:border-blue-400 hover:bg-blue-50/40 flex items-center justify-between text-xs font-bold text-slate-800 transition-colors group"
              >
                <span>Open Evidence Explorer</span>
                <ArrowRight className="w-3.5 h-3.5 text-slate-400 group-hover:text-blue-600 group-hover:translate-x-0.5 transition-all" />
              </Link>

              <Link
                href={`/research/${researchId}/checklist`}
                className="w-full p-3 rounded-xl border border-blue-200 bg-blue-50/50 hover:bg-blue-100/60 flex items-center justify-between text-xs font-bold text-blue-700 transition-colors group"
              >
                <span>View Verification Checklist</span>
                <ArrowRight className="w-3.5 h-3.5 text-blue-500 group-hover:translate-x-0.5 transition-all" />
              </Link>

              <Link
                href={`/research/${researchId}/sources`}
                className="w-full p-3 rounded-xl border border-slate-200 hover:border-slate-300 hover:bg-slate-50 flex items-center justify-between text-xs font-bold text-slate-800 transition-colors group"
              >
                <span>Review Sources ({sourcesCount || 4})</span>
                <ArrowRight className="w-3.5 h-3.5 text-slate-400 group-hover:translate-x-0.5 transition-all" />
              </Link>
            </div>
          </div>
        </div>
      </main>
    </>
  );
}
